#!/usr/bin/env node
/**
 * Two-artifact build, same shape the viewer plugin validated:
 *
 *  - host half  lib/index.js   ordinary ESM, Node externals unresolved;
 *  - client half lib/client.js CJS wrapped in the shell module-loader facade,
 *    with pdf.js bundled and its worker inlined as a string (cite-lens's
 *    validated blob-URL approach — no static file route needed).
 *
 * Everything the module table cannot answer must be inlined; the table's
 * answerable specifiers stay external (react, the dsh client packages).
 */
import { build } from 'esbuild'
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { join, relative } from 'node:path'
import { transform } from 'lightningcss'

const root = fileURLToPath(new URL('..', import.meta.url))
const manifest = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'))
const id = manifest.name

mkdirSync(join(root, 'lib'), { recursive: true })

/** Host externals: everything a real install materializes on disk. */
const NODE_EXTERNAL = ['@deepseek-ai/cordis']

await build({
  absWorkingDir: root,
  entryPoints: ['src/index.ts'],
  outfile: 'lib/index.js',
  bundle: true,
  format: 'esm',
  platform: 'node',
  target: 'node24',
  external: NODE_EXTERNAL,
  sourcemap: false,
  logLevel: 'info',
})

await build({
  absWorkingDir: root,
  entryPoints: ['src/migrate-profile.ts'],
  outfile: 'lib/migrate-profile.cjs',
  bundle: true, format: 'cjs', platform: 'node', target: 'node24',
  logLevel: 'info',
})

const result = await build({
  absWorkingDir: root,
  entryPoints: ['src/client/index.ts'],
  bundle: true,
  format: 'cjs',
  platform: 'browser',
  target: 'es2022',
  external: ['react', 'react-dom', '@deepseek-ai/dsh-client-ui-primitives', 'cordis'],
  plugins: [{
    name: 'inline-css-modules',
    setup(plugin) {
      plugin.onLoad({ filter: /\.module\.css$/ }, ({ path }) => {
        const filename = relative(root, path).replaceAll('\\', '/')
        const { code, exports } = transform({ filename, code: readFileSync(path), cssModules: { pattern: '[hash]_[local]' }, minify: true })
        // The native transformer returns map keys in varying order. Stabilize
        // code generation so independent builds produce the same client bytes.
        const classes = Object.fromEntries(Object.entries(exports ?? {}).sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0).map(([key, value]) => [key, value.name]))
        return { loader: 'js', contents: `
          const key = ${JSON.stringify(id + '/' + filename)};
          if (!document.querySelector('style[data-plugin-css=' + JSON.stringify(key) + ']')) {
            const style = document.createElement('style'); style.dataset.pluginCss = key;
            style.textContent = ${JSON.stringify(code.toString())}; document.head.append(style);
          }
          export default ${JSON.stringify(classes)};
        ` }
      })
    },
  }],
  loader: { '.css': 'text' },
  minify: true,
  legalComments: 'none',
  write: false,
  logLevel: 'error',
  supported: { 'top-level-await': false },
  define: { 'process.env.NODE_ENV': '"production"', __SIDENOTE_VERSION__: JSON.stringify(manifest.version) },
})

const worker = readFileSync(join(root, 'node_modules/pdfjs-dist/build/pdf.worker.min.mjs'), 'utf8')
const body = result.outputFiles[0].text
const wrapped = `// dsh-paper-margin — browser half. GENERATED by scripts/build.mjs from src/client; edit those, then npm run build.
// Bundles pdf.js (Apache-2.0, Mozilla Foundation, https://mozilla.github.io/pdf.js/).
window.__ModuleLoader__.load({
  id: ${JSON.stringify(id)},
  factory: (require) => {
    var module = { exports: {} };
    var exports = module.exports;
    var __DSH_PAPER_MARGIN_WORKER__ = ${JSON.stringify(worker)};
${body}
    return module.exports;
  },
});
`
writeFileSync(join(root, 'lib/client.js'), wrapped)
console.log(`built ${id}: lib/index.js + lib/client.js (${(wrapped.length / 1024).toFixed(0)} KB)`)
